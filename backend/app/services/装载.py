def 装一批(体: dict) -> dict:
    """入流一批互动事件：按房间分组，每房一张串行票，票内推进水位线/关窗/入窗/旁路。

    口径（类 Flink，并发架构甲：冲突整票回滚 + 命运码硬路由）：
    - 同房入流与关窗扫描互斥；一房间一票，票内全部状态变迁同票提交
    - 抢锁/写保留/窗版本冲突 → 该房本票整票回滚：事件不入库、水位窗态不动，
      仅在关窗并发账留无效票，可原样整票重试，禁止半截
    - 冲突处置成功必须写「入流命运账」：整票全部事件记 命运码=未入（与冲突世代同票提交）
    - 重推一律先吃命运码：已入→幂等跳过；旁路→只许旁路入口；未入→当全新入流
    - 成功票内每个事件的命运（已入/旁路）与窗合计、水位同票写入命运账，禁止空账
    - 水位 = 已见最大事件时；窗 [起,止) 在 水位>=止 时关闭发射
    - 关闭后至 水位>=止+允许迟到 仍可迟到修正并发撤回；越过则旁路
    """
    批次编号 = 体.get("批次编号") or f"批-{此刻().replace(':', '').replace('-', '')}"
    批次账号 = 体.get("账号") or "系统"
    事件列表 = 体.get("事件") or []
    报告 = {
        "批次编号": 批次编号,
        "入流": 0,
        "入窗": 0,
        "旁路": 0,
        "撤回": 0,
        "新关窗": 0,
        "幂等跳过": 0,
        "冲突票数": 0,
        "命运账写入": 0,
        "明细": [],
    }


    房事件: "OrderedDict[str, list]" = OrderedDict()
    未知 = []
    探 = 连接()
    try:
        已知房 = {r["房间键"] for r in 探.execute("SELECT 房间键 FROM 直播间")}
    finally:
        探.close()
    for ev in 事件列表:
        (房事件.setdefault(ev["房间键"], []) if ev["房间键"] in 已知房 else 未知).append(ev)

    for ev in 未知:
        报告["旁路"] += 1
        报告["明细"].append({"事件编号": ev.get("事件编号"), "命运": "旁路-未知房"})

    if 未知:
        报告["命运账写入"] += _落未知房旁路(未知, 批次编号, 批次账号)

    for 房间键, 本组 in 房事件.items():
        管 = 并发.同房票(房间键, "入流", 批次编号)
        try:
            with 管 as 囊:
                _装一房(囊, 本组, 批次账号)
        except 并发.冲突异常:

            pass
        if not 管.有效:

            回滚明细 = [
                {"事件编号": ev.get("事件编号"), "命运": "整票回滚-冲突", "窗键": ""}
                for ev in 本组
            ]
            # 票内可能已记过若干 已入 命运，但整票回滚后一律不成立，覆写为回滚明细
            管.票囊.补录命运(回滚明细)

            写数 = _落冲突命运(房间键, 管.票号, 批次编号, 本组, 批次账号)
            报告["命运账写入"] += 写数
            报告["冲突票数"] += 1
            报告["明细"].append({
                "房间键": 房间键,
                "票号": 管.票号,
                "命运": "整票回滚-冲突",
                "冲突来源": 管.冲突来源,
                "事件编号": [ev.get("事件编号") for ev in 本组],
                "命运账": "未入×%d" % 写数,
            })
        else:
            囊 = 管.票囊
            报告["入流"] += 囊.入流数
            报告["入窗"] += 囊.入窗数
            报告["旁路"] += 囊.旁路数
            报告["撤回"] += 囊.撤回数
            报告["新关窗"] += 囊.关窗数
            报告["幂等跳过"] += 囊.幂等跳过数
            报告["命运账写入"] += 囊.命运账写数
            报告["明细"].extend(囊.明细)

    
    
    
    conn = 连接()
    conn.execute("PRAGMA busy_timeout = 30000")
    try:
        
        旧 = conn.execute(
            "SELECT 编号 FROM 装载批次 WHERE 编号=?", (批次编号,)
        ).fetchone()
        if 旧:
            conn.execute(
                "UPDATE 装载批次 SET 时刻=?, 报告=? WHERE 编号=?",
                (此刻(), json.dumps(报告, ensure_ascii=False), 批次编号),
            )
        else:
            conn.execute(
                "INSERT INTO 装载批次(编号, 时刻, 报告) VALUES (?,?,?)",
                (批次编号, 此刻(), json.dumps(报告, ensure_ascii=False)),
            )
        conn.commit()
    finally:
        conn.close()
    return 报告


def _装一房(囊: 并发.票囊, 事件列表: list, 账号: str = "系统") -> None:
    """票内处理同房全部事件。任何异常向外抛 → 同房票上下文整票回滚。

    路由纪律：每事件先读入流命运账最新命运码，再按「已入→幂等跳过 /
    旁路→只许旁路入口 / 未入→当全新入流」处置；本票每个事件的最终命运
    与窗合计、水位一起同票写入入流命运账（禁止空账）。
    """
    conn = 囊.conn
    房间键 = 囊.房间键
    站 = {r["键"]: r["值"] for r in conn.execute("SELECT 键, 值 FROM 站规")}
    窗长 = int(站.get("窗长秒", "60"))
    默许迟到 = int(站.get("允许迟到秒", "30"))

    房 = conn.execute("SELECT * FROM 直播间 WHERE 房间键=?", (房间键,)).fetchone()
    水位 = conn.execute("SELECT * FROM 水位线 WHERE 房间键=?", (房间键,)).fetchone()
    if not 水位:
        并发.执写(
            conn,
            "INSERT INTO 水位线(房间键, 事件时水位, 允许迟到秒, 更新处理时) VALUES (?,?,?,?)",
            (房间键, 房["开播事件时"], 默许迟到, 此刻()),
        )
        水位 = conn.execute("SELECT * FROM 水位线 WHERE 房间键=?", (房间键,)).fetchone()

    允许迟到 = int(水位["允许迟到秒"])
    世代 = 命运账.读世代(conn, 房间键)

    for ev in 事件列表:
        事件时 = ev["事件时"]
        处理时 = ev.get("处理时") or 此刻()
        事件编号 = ev["事件编号"]
        点赞 = int(ev.get("点赞增量") or 0)
        送礼 = int(ev.get("送礼额") or 0)
        类型 = ev.get("事件类型") or "点赞"
        观众 = ev.get("观众键") or ""

        旧码 = 命运账.命运码(conn, 事件编号)
        路由 = 命运账.路由(旧码) if 旧码 else 命运账.路由(命运账.未入)

        # 硬路由·已入：重推必须幂等跳过，不得再抬水位/改窗合计/双加
        if 路由["动作"] == "幂等跳过":
            囊.幂等跳过数 += 1
            囊.明细.append({"事件编号": 事件编号, "命运": "幂等跳过", "命运码": 命运账.已入})
            囊.记命运(事件编号, "幂等跳过", 命运码=命运账.已入, 账号=观众)
            continue

        # 硬路由·旁路：只许走旁路入口，绝不再入窗
        if 路由["须走旁路"]:
            if conn.execute("SELECT 1 FROM 互动事件 WHERE 事件编号=?", (事件编号,)).fetchone():
                # 已由先前的旁路入口落地：不得重复写，只留旁路身份
                囊.幂等跳过数 += 1
                囊.明细.append({"事件编号": 事件编号, "命运": "旁路-幂等跳过", "命运码": 命运账.旁路})
                囊.记命运(事件编号, "已旁路", 命运码=命运账.旁路, 账号=观众)
                continue
            _入旁路(
                囊, ev, 房间键, 事件时, 处理时, 事件编号, 点赞, 送礼, 类型, 观众,
                原因="命运=旁路重推",
            )
            囊.旁路数 += 1
            囊.记命运(事件编号, "已旁路", 命运码=命运账.旁路, 账号=观众)
            囊.明细.append({"事件编号": 事件编号, "命运": "已旁路", "命运码": 命运账.旁路})
            continue

        # 历史遗留兜底：无命运账行但互动事件已落库 → 以库内命运回填命运码后按码路由
        旧事 = conn.execute(
            "SELECT 命运, 窗键 FROM 互动事件 WHERE 事件编号=?", (事件编号,)
        ).fetchone()
        if 旧事:
            回填码 = 命运账.归一命运码(旧事["命运"])
            if 回填码 == 命运账.已入:
                囊.幂等跳过数 += 1
                囊.记命运(事件编号, "幂等跳过", 命运码=命运账.已入, 账号=观众)
                囊.明细.append({"事件编号": 事件编号, "命运": "幂等跳过", "命运码": 命运账.已入})
                continue
            if 回填码 == 命运账.旁路:
                囊.幂等跳过数 += 1
                囊.记命运(事件编号, "已旁路", 命运码=命运账.旁路, 账号=观众)
                囊.明细.append({"事件编号": 事件编号, "命运": "旁路-幂等跳过", "命运码": 命运账.旁路})
                continue

        # 硬路由·未入：当全新入流
        水位 = conn.execute("SELECT * FROM 水位线 WHERE 房间键=?", (房间键,)).fetchone()
        当前水位 = 水位["事件时水位"]
        if 时间.解析(事件时) > 时间.解析(当前水位):
            当前水位 = 事件时
            并发.执写(
                conn,
                "UPDATE 水位线 SET 事件时水位=?, 更新处理时=? WHERE 房间键=?",
                (当前水位, 处理时, 房间键),
            )

        热度窗.尝试关窗(conn, 房间键, 当前水位, 允许迟到, 窗长, 处理时, 囊)

        窗起 = 时间.对齐窗起(事件时, 窗长)
        窗止 = 时间.加秒(窗起, 窗长)
        wk = 时间.窗键(房间键, 窗起)

        if 热度窗.已过旁路界(当前水位, 窗止, 允许迟到):
            _入旁路(
                囊, ev, 房间键, 事件时, 处理时, 事件编号, 点赞, 送礼, 类型, 观众,
                原因="超允许迟到", 窗止=窗止, 旁路界=时间.加秒(窗止, 允许迟到),
                水位=当前水位,
            )
            囊.旁路数 += 1
            囊.记命运(事件编号, "已旁路", 命运码=命运账.旁路, 账号=观众)
            囊.明细.append({"事件编号": 事件编号, "命运": "已旁路", "窗键本应": wk})
            continue

        窗 = conn.execute("SELECT * FROM 热度窗 WHERE 窗键=?", (wk,)).fetchone()
        if not 窗:
            并发.执写(
                conn,
                """INSERT INTO 热度窗(窗键,房间键,窗起事件时,窗止事件时,状态,点赞合计,送礼合计,事件笔数,版本)
                   VALUES (?,?,?,?, '开启', 0, 0, 0, 0)""",
                (wk, 房间键, 窗起, 窗止),
            )
            热度窗.尝试关窗(conn, 房间键, 当前水位, 允许迟到, 窗长, 处理时, 囊)
            窗 = conn.execute("SELECT * FROM 热度窗 WHERE 窗键=?", (wk,)).fetchone()

        if 窗["状态"] == "已关闭":
            旧赞, 旧送 = 窗["点赞合计"], 窗["送礼合计"]
            新赞, 新送 = 旧赞 + 点赞, 旧送 + 送礼
            旧版本 = int(窗["版本"])
            cur = 并发.执写(
                conn,
                """UPDATE 热度窗 SET 点赞合计=?, 送礼合计=?, 事件笔数=事件笔数+1, 版本=?
                   WHERE 窗键=? AND 版本=? AND 状态='已关闭'""",
                (新赞, 新送, 旧版本 + 1, wk, 旧版本),
            )
            并发.乐观版本过期(cur, f"窗{wk}迟到修正版本过期")
            并发.执写(
                conn,
                """INSERT INTO 撤回单(窗键,房间键,原因,旧点赞,新点赞,旧送礼,新送礼,处理时,事件编号)
                   VALUES (?,?,?,?,?,?,?,?,?)""",
                (wk, 房间键, "迟到修正", 旧赞, 新赞, 旧送, 新送, 处理时, 事件编号),
            )
            并发.执写(
                conn,
                """INSERT INTO 互动事件(事件编号,房间键,事件类型,事件时,处理时,观众键,点赞增量,送礼额,命运,窗键,批次编号)
                   VALUES (?,?,?,?,?,?,?,?,?,?,?)""",
                (
                    事件编号, 房间键, 类型, 事件时, 处理时,
                    观众, 点赞, 送礼, "已入窗", wk, 囊.批次编号,
                ),
            )
            囊.入窗数 += 1
            囊.入流数 += 1
            囊.撤回数 += 1
            囊.记命运(事件编号, "迟到修正撤回", wk, 命运码=命运账.已入, 账号=观众)
            囊.明细.append({"事件编号": 事件编号, "命运": "迟到修正撤回", "窗键": wk})
        else:
            旧版本 = int(窗["版本"])
            cur = 并发.执写(
                conn,
                """UPDATE 热度窗 SET 点赞合计=点赞合计+?, 送礼合计=送礼合计+?, 事件笔数=事件笔数+1, 版本=?
                   WHERE 窗键=? AND 版本=? AND 状态='开启'""",
                (点赞, 送礼, 旧版本 + 1, wk, 旧版本),
            )
            并发.乐观版本过期(cur, f"窗{wk}入窗版本过期")
            并发.执写(
                conn,
                """INSERT INTO 互动事件(事件编号,房间键,事件类型,事件时,处理时,观众键,点赞增量,送礼额,命运,窗键,批次编号)
                   VALUES (?,?,?,?,?,?,?,?,?,?,?)""",
                (
                    事件编号, 房间键, 类型, 事件时, 处理时,
                    观众, 点赞, 送礼, "已入窗", wk, 囊.批次编号,
                ),
            )
            囊.入窗数 += 1
            囊.入流数 += 1
            囊.记命运(事件编号, "已入窗", wk, 命运码=命运账.已入, 账号=观众)
            囊.明细.append({"事件编号": 事件编号, "命运": "已入窗", "窗键": wk})

    # 冲突处置成功：整票全部事件命运与窗合计、水位同票写入流命运账（禁止空账）
    命运账.记一票(
        conn,
        房间键=房间键,
        票号=囊.票号,
        批次编号=囊.批次编号,
        世代=世代,
        命运明细=[
            {
                "事件编号": d["事件编号"],
                "命运码": d.get("命运码") or 命运账.归一命运码(d["命运"]),
                "账号": d.get("账号", ""),
                "窗键": d.get("窗键", ""),
                "备注": d["命运"],
            }
            for d in 囊.事件命运
        ],
    )
    囊.命运账写数 = len(囊.事件命运)


def _入旁路(囊, ev, 房间键, 事件时, 处理时, 事件编号, 点赞, 送礼, 类型, 观众,
            原因: str, **载荷) -> None:
    """旁路入口（唯一合法旁路写点）：写互动事件（命运=已旁路、窗键为空）+ 旁路匣。"""
    conn = 囊.conn
    并发.执写(
        conn,
        """INSERT INTO 互动事件(事件编号,房间键,事件类型,事件时,处理时,观众键,点赞增量,送礼额,命运,窗键,批次编号)
           VALUES (?,?,?,?,?,?,?,?,?,?,?)""",
        (
            事件编号, 房间键, 类型, 事件时, 处理时,
            观众, 点赞, 送礼, "已旁路", "", 囊.批次编号,
        ),
    )
    载荷体 = {"事件编号": 事件编号, "事件时": 事件时, "命运码": 命运账.旁路}
    载荷体.update({k: v for k, v in 载荷.items() if v is not None})
    并发.执写(
        conn,
        "INSERT INTO 旁路匣(原因, 载荷, 时刻) VALUES (?,?,?)",
        (原因, json.dumps(载荷体, ensure_ascii=False), 处理时),
    )

def _落未知房旁路(未知: list, 批次编号: str, 账号: str) -> int:
    """未知直播间：只走旁路入口，并落命运账 命运码=旁路（与旁路匣同事务）。"""
    conn = 连接()
    conn.execute("PRAGMA busy_timeout = 30000")
    n = 0
    try:
        for ev in 未知:
            编号 = ev.get("事件编号") or ""
            并发.执写(
                conn,
                "INSERT INTO 旁路匣(原因, 载荷, 时刻) VALUES (?,?,?)",
                (
                    "未知直播间",
                    json.dumps(
                        {"事件编号": 编号, "载荷": ev, "命运码": 命运账.旁路},
                        ensure_ascii=False,
                    ),
                    此刻(),
                ),
            )
            if 编号:
                命运账.记账(
                    conn,
                    房间键=ev.get("房间键") or "",
                    事件编号=编号,
                    命运码=命运账.旁路,
                    账号=账号,
                    批次编号=批次编号,
                    备注="旁路-未知房",
                )
                n += 1
        conn.commit()
    finally:
        conn.close()
    return n


def _落冲突命运(房间键: str, 票号: str, 批次编号: str, 本组: list, 账号: str) -> int:
    """冲突整票回滚后补记命运账：本票全部事件 命运码=未入，并抬该房冲突世代。

    业务票已整票回滚（事件不入互动事件、窗态水位不动），故未入命运是事实；
    用同一票号写入流命运账，重推时按未入码当全新入流。

    串行化：独立连接 + BEGIN IMMEDIATE + 放大 busy_timeout（与既有的装载批次
    落库同法），保证跨进程/跨票补记不半截；半截失败整笔 ROLLBACK。
    单调守卫：若并发已有 已入/旁路 账行，则不覆写成未入。
    """
    conn = 连接()
    conn.isolation_level = None
    # 冲突对方票可能正持写保留，补记须等其结束而非把「未入」丢在地上
    conn.execute("PRAGMA busy_timeout = 60000")
    try:
        conn.execute("BEGIN IMMEDIATE")
        try:
            n = _补记未入(conn, 房间键, 票号, 批次编号, 本组, 账号)
            conn.execute("COMMIT")
        except Exception:
            conn.execute("ROLLBACK")
            raise
    except sqlite3.OperationalError:
        # 写保留长期不可得：放弃补记；票据回滚事实仍在并发账留痕，重推默认按未入
        return 0
    finally:
        conn.close()
    return n


def _补记未入(conn, 房间键: str, 票号: str, 批次编号: str, 本组: list, 账号: str) -> int:
    世代 = 命运账.抬世代(conn, 房间键, 此刻())
    n = 0
    for ev in 本组:
        编号 = ev.get("事件编号")
        if not 编号:
            continue
        已有 = conn.execute(
            "SELECT 1 FROM 入流命运账 WHERE 事件编号=? AND 命运码 IN ('已入','旁路') LIMIT 1",
            (编号,),
        ).fetchone()
        if 已有:
            continue
        命运账.记账(
            conn,
            房间键=房间键,
            事件编号=编号,
            命运码=命运账.未入,
            冲突世代=世代,
            账号=账号,
            票号=票号,
            批次编号=批次编号,
            备注="冲突整票回滚",
        )
        n += 1
    return n


def _alias_payload(payload: dict) -> dict:
    out = dict(payload or {})
    if "窗键" in out and "window_key" not in out:
        out["window_key"] = out.get("窗键")
    if "房间键" in out and "room_key" not in out:
        out["room_key"] = out.get("房间键")
    if "事件编号" in out and "event_id" not in out:
        out["event_id"] = out.get("事件编号")
    if "aligned" not in out:
        out["aligned"] = True
    return out


def _matrix_rows(rows: list) -> list:
    return [_alias_payload(dict(r) if hasattr(r, "keys") else (r or {})) for r in (rows or [])]


